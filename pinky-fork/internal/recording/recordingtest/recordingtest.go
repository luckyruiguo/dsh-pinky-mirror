// Package recordingtest holds short synthetic video streams for tests:
// ffmpeg's test patterns, not captures of any screen. They are stored as
// base64 because the repository ignores raw .h264 and .hevc files, which
// is how device captures are kept out of it.
//
// testsrc.h264 and testsrc.hevc: 30 frames of testsrc at 96x64, 10 frames a
// second, a key frame every 10 frames, access unit delimiters on:
//
//	ffmpeg -f lavfi -i testsrc=size=96x64:rate=10 -frames:v 30 -pix_fmt yuv420p -c:v libx264 \
//	  -preset ultrafast -g 10 -bf 0 -bsf:v h264_metadata=aud=insert -f h264 testsrc.h264
//	ffmpeg -f lavfi -i testsrc=size=96x64:rate=10 -frames:v 30 -pix_fmt yuv420p -c:v libx265 \
//	  -preset ultrafast -x265-params keyint=10:min-keyint=10:bframes=0 -bsf:v hevc_metadata=aud=insert -f hevc testsrc.hevc
//
// rotated.h264: 10 frames of testsrc2 at 64x96, as a phone sends after a
// rotation.
package recordingtest

import (
	"encoding/base64"
	"strings"

	"github.com/DIYgod/pinky/internal/driver"
	"github.com/DIYgod/pinky/internal/video"
)

// H264 is testsrc.h264, in Annex B.
func H264() []byte { return decode(h264) }

// HEVC is testsrc.hevc, in Annex B.
func HEVC() []byte { return decode(hevc) }

// Rotated is rotated.h264, in Annex B.
func Rotated() []byte { return decode(rotated) }

func decode(s string) []byte {
	b, err := base64.StdEncoding.DecodeString(strings.Join(strings.Fields(s), ""))
	if err != nil {
		panic(err)
	}
	return b
}

// Packets cuts an Annex B stream with access unit delimiters into packets
// the way drivers send them: a configuration packet, then one packet per
// picture, without the delimiters.
func Packets(codec driver.Codec, data []byte) []driver.Packet {
	var out []driver.Packet
	var cfg, pic [][]byte
	key := false
	flush := func() {
		if len(cfg) > 0 {
			out = append(out, driver.Packet{Data: join(cfg), Config: true})
			cfg = nil
		}
		if len(pic) > 0 {
			out = append(out, driver.Packet{Data: join(pic), KeyFrame: key})
			pic, key = nil, false
		}
	}
	for _, nal := range video.SplitNALs(data) {
		typ := video.NALType(codec, nal)
		switch {
		case codec == driver.HEVC && typ == 35, codec != driver.HEVC && typ == 9:
			flush()
		case codec == driver.HEVC && typ >= 32 && typ <= 34, codec != driver.HEVC && (typ == 7 || typ == 8):
			cfg = append(cfg, nal)
		default:
			pic = append(pic, nal)
			if codec == driver.HEVC {
				key = key || (typ >= 16 && typ <= 23)
			} else {
				key = key || typ == 5
			}
		}
	}
	flush()
	return out
}

func join(nals [][]byte) []byte {
	var b []byte
	for _, n := range nals {
		b = append(append(b, 0, 0, 0, 1), n...)
	}
	return b
}

